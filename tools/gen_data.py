"""Generate js/models.js (key matrix, LED location codes and positions) from pixeltris/GK6X device data.

Usage: python3 -I tools/gen_data.py <path-to-GK6X/Build/Data> [name-filter]
The filter (default "61") selects models by name. Lighting effects aren't taken from vendor data; they are
generated in js/effects.js.
"""
import json
import os
import sys

data_dir = sys.argv[1]
name_filter = sys.argv[2] if len(sys.argv) > 2 else "61"
js_dir = os.path.join(os.path.dirname(__file__), "..", "js")


def load(path):
    with open(path, encoding="utf-8-sig") as f:
        return json.load(f)


def write(name, var, value):
    path = os.path.normpath(os.path.join(js_dir, name))
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/gen_data.py from pixeltris/GK6X device data. Do not edit.\n")
        f.write(f"export const {var} = " + json.dumps(value, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print(f"{len(value)} entries -> {path}")


# ---- models ----

models = {}
for m in load(os.path.join(data_dir, "device", "modellist.json")):
    if name_filter not in m["Name"]:
        continue
    data = os.path.join(data_dir, "device", str(m["ModelID"]), "data")
    try:
        keys = load(os.path.join(data, "keymap.js"))
    except (OSError, ValueError):
        continue  # missing, or declared as JS rather than JSON
    is_led = lambda k: "LED" in k["KeyName"].upper()
    leds = [k for k in keys if is_led(k)]
    keys = [k for k in keys if k["LogicCode"] >= 0 and not is_led(k)]
    x0 = min(k["Position"]["Left"] for k in keys + leds)
    y0 = min(k["Position"]["Top"] for k in keys + leds)
    pos = lambda k: [k["Position"]["Left"] - x0, k["Position"]["Top"] - y0, k["Position"]["Width"], k["Position"]["Height"]]

    models[m["ModelID"]] = {
        "name": m["Name"],
        "fw": int(m["FWID"], 16),
        # [logicCode, label, x, y, w, h, locationCode]; location codes address LEDs
        "keys": [[k["LogicCode"], k["Show"], *pos(k), k["LocationCode"]] for k in keys],
        # side/underglow LEDs that aren't keys: [locationCode, x, y, w, h]
        "leds": [[k["LocationCode"], *pos(k)] for k in leds],
    }

write("models.js", "MODELS", models)
